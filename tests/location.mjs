import assert from "node:assert/strict";

const base = process.env.SMOKE_BASE_URL || "http://localhost:3000";
const response = await fetch(new URL("/contact", base));
assert.equal(response.status, 200, "contact page loads");
const html = await response.text();
assert.match(html, /<address>63 หมู่ 2 ตำบลดอนกระเบื้อง<br\s*\/?>(?:<!-- -->)?อำเภอบ้านโป่ง/, "visible street, village and district");
assert.match(html, /ราชบุรี/, "province is visible");
assert.match(html, /70110/, "postal code is visible");
const iframe = html.match(/<iframe\b[^>]*>/)?.[0];
assert.ok(iframe, "real embedded map exists");
assert.match(iframe, /loading="lazy"/, "map defers loading");
assert.match(iframe, /title="[^"]+"/, "map has accessible title");
assert.match(iframe, /q=13\.7638941,99\.9060657/, "map pins the verified business, not the camera center");
assert.match(html, /href="https:\/\/maps\.app\.goo\.gl\/fFeFDjb3yCZ6AY5c8"/, "original verified Maps link");
assert.match(html, /href="https:\/\/www\.google\.com\/maps\/dir\/\?api=1&amp;destination=13\.7638941,99\.9060657"/, "directions use exact coordinates");
const schemas = [...html.matchAll(/<script[^>]*type="application\/ld\+json"[^>]*>([\s\S]*?)<\/script>/g)].map((match) => JSON.parse(match[1]));
assert.ok(schemas.some((schema) => schema["@type"] === "Organization"), "existing organization remains");
const business = schemas.find((schema) => schema["@type"] === "HomeAndConstructionBusiness");
assert.ok(business, "local business structured data exists");
assert.deepEqual(business.geo, { "@type": "GeoCoordinates", latitude: 13.7638941, longitude: 99.9060657 });
assert.deepEqual(business.address, { "@type": "PostalAddress", streetAddress: "63 หมู่ 2 ตำบลดอนกระเบื้อง", addressLocality: "อำเภอบ้านโป่ง", addressRegion: "ราชบุรี", postalCode: "70110", addressCountry: "TH" });
assert.equal(business.telephone, "+66924127392");
assert.equal(business.hasMap, "https://maps.app.goo.gl/fFeFDjb3yCZ6AY5c8");
assert.ok(!business.openingHours && !business.aggregateRating && !business.areaServed, "no unverified hours, ratings, or coverage");
const home = await fetch(new URL("/", base)).then((r) => r.text());
const footer = home.match(/<footer\b[\s\S]*?<\/footer>/)?.[0];
assert.ok(footer?.includes("63 หมู่ 2 ตำบลดอนกระเบื้อง อำเภอบ้านโป่ง ราชบุรี 70110"), "site-wide footer contains complete address");
assert.ok(business.sameAs.includes("https://www.facebook.com/profile.php?id=100086327531403"), "official business Facebook page in local schema");
assert.ok(footer?.includes("https://www.facebook.com/profile.php?id=100086327531403"), "footer links to official business Facebook page");
assert.ok(footer?.includes("https://maps.app.goo.gl/fFeFDjb3yCZ6AY5c8"), "site-wide footer links to Maps");
console.log("PASS verified business address, exact map pin, navigation, local schema and global footer");
